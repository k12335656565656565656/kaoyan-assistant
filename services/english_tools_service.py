def load_essay_topics(topics_file: str | Path = "data/essay_topics.json") -> dict:
    path = Path(topics_file)
    if not path.exists():
        return {}
    try:
        return json.loads(path.read_text(encoding="utf-8"))
    except Exception:
        return {}


def extract_essay_text_from_image(img_data_base64: str) -> str:
    prompt = "请识别这张照片中的英语作文内容，只输出英文文本，保持原文格式和段落分隔。"
