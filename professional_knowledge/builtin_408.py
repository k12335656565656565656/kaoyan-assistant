def is_408_subject(subject: str | None) -> bool:
    return str(subject or "").strip() in BUILTIN_408_SUBJECTS


def _point(
    chapter: str,
    name: str,
    definition: str,
    *,
    exam: list[str],
    keywords: list[str],
    pitfalls: list[str],
    related: list[str] | None = None,
) -> dict:
    study_lines = [
        f"核心理解：{definition}",
        f"复习抓手：先抓住 {', '.join(keywords[:4])} 这几个词，再回到题目里判断它考的是概念辨析、过程推演还是计算。",
        f"常见考法：{'；'.join(exam)}。",
        f"易错提醒：{'；'.join(pitfalls)}",
    ]
    if related:
        study_lines.append(f"关联知识：{', '.join(related)}。复习时建议放在同一张图或同一组表里比较。")
    study_lines.append(
        "掌握标准：能不用原话讲清定义，能写出关键步骤或公式，遇到选择题能说明排除理由，遇到综合题能把条件转成图、表、地址、窗口或状态变化。"
    )
    return {
        "subject": "408综合",
        "chapter_name": chapter,
        "knowledge_name": name,
        "knowledge_type": "408内置知识点",
        "core_definition": "\n\n".join(study_lines),
        "exam_question_styles": exam,
        "keywords": keywords,
        "pitfalls": pitfalls,
        "related_concepts": related or [],
        "source_text": "408内置学习库：按数据结构、计算机组成原理、操作系统、计算机网络四门主干整理。",
        "source_location": chapter,
        "tags": [chapter, "408", "内置学习库"],
        "review_priority": "高",
    }


