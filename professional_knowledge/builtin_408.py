def ensure_builtin_408_points(conn, user_id: int, subject: str | None) -> int:
    """Seed built-in 408 rows for the current user if the subject is 408."""
    if not is_408_subject(subject):
        return 0
    target_subject = subject or "408综合"
    points = [dict(point, subject=target_subject) for point in BUILTIN_408_POINTS]
    ensure_knowledge_schema(conn)
    existing = conn.execute(
        """SELECT COUNT(*)
           FROM user_knowledge
           WHERE user_id=? AND subject=? AND source_type=?""",
        (user_id, target_subject, BUILTIN_408_SOURCE_TYPE),
    ).fetchone()[0]
    if existing == len(points):
        return 0
    if existing:
        conn.execute(
            """DELETE FROM user_knowledge
               WHERE user_id=? AND subject=? AND source_type=?""",
            (user_id, target_subject, BUILTIN_408_SOURCE_TYPE),
        )

    return save_confirmed_knowledge_points(
        conn,
        user_id=user_id,
        points=points,
        material_meta={
            "subject": target_subject,
            "subject_key": "builtin_408",
            "chapter_name": "408内置学习库",
            "material_filename": "408内置学习库",
            "content_hash": BUILTIN_408_CONTENT_HASH,
            "source_type": BUILTIN_408_SOURCE_TYPE,
            "process_method": BUILTIN_408_PROCESS_METHOD,
        },
        strict=False,
        finalize_material=False,
    )
